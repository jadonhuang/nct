using Nct.Extentions;
using Nct.Http.ApiDescription;
using Nct.Http.ScriptProxy;
using Nct.Ioc;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Nct.AspNetCore.ScriptProxy
{
    public class ApiScriptBuilder : IApiScriptBuilder, ISingletonDependency
    {

        private readonly IApiDescriptionModelProvider _descptProvider;



        public ApiScriptBuilder(IApiDescriptionModelProvider descptProvider)
        {
            _descptProvider = descptProvider;
        }



        private Dictionary<string, ModuleApiDescription> GetMoudels()
        {

            return _descptProvider.Create().Modules;
        }



        public string Build(string module, bool addModulePrefix)
        {
            var script = new StringBuilder();
            var modules = GetMoudels();

            script.AppendLine("/* This file is automatically generated */");
            script.AppendLine();

            foreach (var m in modules.Values)
            {

                BuildModuleScript(script, m, module, addModulePrefix);

            }

            return script.ToString();
        }


        private static void BuildModuleScript(StringBuilder script, ModuleApiDescription module, string filterModule, bool addModulePrefix)
        {
            script.AppendLine();
            foreach (var controller in module.Controllers.Values)
            {
                if (filterModule.IsNotEmpty() && !controller.Name.IgnoreCaseEqual(filterModule)) continue;
                BuildControllerScript(script, module, controller, addModulePrefix);

            }
        }

        private static void BuildControllerScript(StringBuilder script, ModuleApiDescription module, ControllerApiDescription controller, bool addModulePrefix)
        {
            script.AppendLine($"var ${controller.Name}Api={{");
            foreach (var action in controller.Actions.Values)
            {
                BuildActionScript(script, module, action, addModulePrefix);
            }
            script.AppendLine("}");
            script.AppendLine();
        }

        private static void BuildActionScript(StringBuilder script, ModuleApiDescription module, ActionApiDescription action, bool addModulePrefix)
        {

            var parameters = string.Join(",", action.Parameters.Select(m => m.Name));
            script.Append($"{action.Name}:function(");
            script.Append(parameters);
            script.AppendLine("){");

            var actionUrl = action.Url;
            if (addModulePrefix)
            {
                actionUrl = module.Name + '/' + actionUrl;
            }

            bool hasParam = action.Parameters.Count > 0;

            if (action.Method == "POST")
            {

                var query = "";
                var simpleParams = action.Parameters.Where(m => m.IsSimpleType);
                foreach (var p in simpleParams)
                {
                    query += $"+'{(query == "" ? "?" : "&")}{p.Name}='+encodeURIComponent({p.Name})";
                }

                parameters = string.Join(",", action.Parameters.Where(m => !m.IsSimpleType).Select(m => m.Name));

                if (parameters.IsNotEmpty())
                {
                    parameters = $",{parameters}";

                }

                script.AppendLine($"return $apiPost('{actionUrl}'{query}{parameters})");

            }
            else
            {

                if (hasParam)
                {
                    parameters = $",{{{parameters}}}";
                }

                script.AppendLine($"return $apiGet('{actionUrl}'{parameters})");

            }
            script.AppendLine("},");
        }

    }
}
